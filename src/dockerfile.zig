test "extra files cannot overwrite project roots or overlap each other" {
    for ([_][]const ExtraFile{
        &.{.{ .source = "replacement.py", .destination = "/app/server.py" }},
        &.{.{ .source = "replacement", .destination = "/runtime/lib.so" }},
        &.{ .{ .source = "a", .destination = "/etc/app.conf" }, .{ .source = "b", .destination = "/etc/app.conf" } },
        &.{ .{ .source = "a", .destination = "/etc/config" }, .{ .source = "b", .destination = "/etc/config/app.conf" } },
    }) |files| {
        try std.testing.expectError(error.InvalidExtraDestination, generate(std.testing.allocator, .{ .kind = .static_elf }, .{
            .input = "server",
            .extra_files = files,
        }));
    }
