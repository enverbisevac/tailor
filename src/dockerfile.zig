const std = @import("std");
const artifact = @import("artifact.zig");

pub const Options = struct {
    input: []const u8,
    base: ?[]const u8 = null,
    builder_base: ?[]const u8 = null,
    entrypoint: ?[]const u8 = null,
    extra_files: []const ExtraFile = &.{},
    native_files: []const @import("dependencies.zig").File = &.{},
    native_root: ?[]const u8 = null,
};

pub const ExtraFile = struct {
    source: []const u8,
    destination: []const u8,
};

pub const GenerateError = error{
    ExecutableStack,
    InvalidBase,
    InvalidEntrypoint,
    RuntimeBaseRequired,
    BuilderBaseRequired,
    InvalidExtraDestination,
} || std.mem.Allocator.Error || std.Io.Writer.Error;

pub fn generate(
    allocator: std.mem.Allocator,
    inspection: artifact.Inspection,
    options: Options,
) GenerateError![]u8 {
    if (inspection.has_executable_stack) return error.ExecutableStack;
    for (options.extra_files, 0..) |file, index| {
        try validateExtraDestination(file.destination, "/app");
        try validateExtraDestination(file.destination, "/runtime");
        for (options.extra_files[0..index]) |previous| {
            if (pathsOverlap(file.destination, previous.destination)) return error.InvalidExtraDestination;
        }
        for (options.native_files) |native| {
            if (pathsOverlap(file.destination, native.destination)) return error.InvalidExtraDestination;
        }
    }

    var output: std.Io.Writer.Allocating = .init(allocator);
    errdefer output.deinit();
    const writer = &output.writer;

    try writer.writeAll("# syntax=docker/dockerfile:1.7@sha256:a57df69d0ea827fb7266491f2813635de6f17269be881f696fbfdf2d83dda33e\n");
    try writer.writeAll("# Generated by Tailor. Regenerate instead of editing manually.\n");
    try writer.writeAll("# Review the pinned base and resolved runtime dependencies before publishing.\n\n");

    switch (inspection.kind) {
        .static_elf => try generateStaticElf(writer, options),
        .dynamic_elf => try generateDynamicElf(writer, options),
        .jar => try generateJar(writer, options),
        .node_project => try generateNode(writer, inspection, options),
        .python_project => try generatePython(writer, inspection, options),
    }

    return output.toOwnedSlice();
}

fn generateStaticElf(writer: *std.Io.Writer, options: Options) !void {
    try writer.writeAll("# Runtime: one static executable in an empty filesystem.\n");
    try writer.writeAll("FROM scratch AS runtime\n\n");
    try writer.writeAll("COPY --chown=65532:65532 --chmod=0555 ");
    try writeJsonString(writer, options.input);
    try writer.writeAll(" /app/application\n");
    try generateExtraFiles(writer, options.extra_files, "/app/application");
    try generateNativeFiles(writer, options);
    try writer.writeByte('\n');
    try writer.writeAll("USER 65532:65532\n");
    try writer.writeAll("ENTRYPOINT [\"/app/application\"]\n");
}

fn generateDynamicElf(writer: *std.Io.Writer, options: Options) !void {
    const base = if (options.base == null and options.native_files.len > 0) "scratch" else try requirePinnedBase(options.base);
    try writer.writeAll("# Runtime: executable plus its explicitly pinned system runtime.\n");
    try writer.print("FROM {s} AS runtime\n\n", .{base});
    try writer.writeAll("COPY --chown=65532:65532 --chmod=0555 ");
    try writeJsonString(writer, options.input);
    try writer.writeAll(" /app/application\n");
    try generateExtraFiles(writer, options.extra_files, "/app/application");
    try generateNativeFiles(writer, options);
    try writer.writeByte('\n');
    try writer.writeAll("USER 65532:65532\n");
    try writer.writeAll("ENTRYPOINT [\"/app/application\"]\n");
}

fn generateJar(writer: *std.Io.Writer, options: Options) !void {
    const base = try requirePinnedBase(options.base);
    try writer.writeAll("# Runtime: executable JAR plus its explicitly pinned JRE.\n");
    try writer.print("FROM {s} AS runtime\n\n", .{base});
    // COPY --chmod also applies the mode to a newly created destination
    // directory. Create /app first so a read-only JAR remains traversable.
    try writer.writeAll("WORKDIR /app\n");
    try writer.writeAll("COPY --chown=65532:65532 --chmod=0444 ");
    try writeJsonString(writer, options.input);
    try writer.writeAll(" /app/application.jar\n");
    try generateExtraFiles(writer, options.extra_files, "/app/application.jar");
    try generateNativeFiles(writer, options);
    try writer.writeByte('\n');
    try writer.writeAll("USER 65532:65532\n");
    try writer.writeAll("ENTRYPOINT [\"java\", \"-jar\", \"/app/application.jar\"]\n");
}

fn generatePython(writer: *std.Io.Writer, inspection: artifact.Inspection, options: Options) !void {
    const base = try requirePinnedBase(options.base);
    const builder_base = options.builder_base orelse return error.BuilderBaseRequired;
    _ = try requirePinnedBase(builder_base);
    const entrypoint = options.entrypoint orelse return error.InvalidEntrypoint;
    if (!isPythonModule(entrypoint)) return error.InvalidEntrypoint;
    const lock_name = inspection.python_lock orelse return error.InvalidEntrypoint;

    try writer.writeAll("# Build: install only hash-locked dependencies.\n");
    try writer.print("FROM {s} AS build\n\n", .{builder_base});
    try writer.writeAll("WORKDIR /src\n");
    try writer.writeAll("COPY ");
    try writeJsonString(writer, options.input);
    try writer.writeAll(" /src\n");
    try writer.writeAll("RUN python -m pip install \\\n");
    try writer.writeAll("    --no-compile \\\n");
    try writer.writeAll("    --no-cache-dir \\\n");
    try writer.writeAll("    --require-hashes \\\n");
    try writer.writeAll("    --only-binary=:all: \\\n");
    try writer.writeAll("    --target=/runtime \\\n");
    try writer.print("    -r {s}\n\n", .{lock_name});

    try writer.writeAll("# Runtime: application, dependencies, and the pinned Python runtime only.\n");
    try writer.print("FROM {s} AS runtime\n\n", .{base});
    try writer.writeAll("COPY --from=build --chown=65532:65532 /runtime /runtime\n");
    try writer.writeAll("COPY --chown=65532:65532 ");
    try writeJsonString(writer, options.input);
    try writer.writeAll(" /app\n");
    try generateExtraFiles(writer, options.extra_files, "/runtime");
    try generateNativeFiles(writer, options);
    try writer.writeAll("\nENV PYTHONPATH=/runtime:/app \\\n");
    try writer.writeAll("    PYTHONDONTWRITEBYTECODE=1 \\\n");
    try writer.writeAll("    PYTHONUNBUFFERED=1 \\\n");
    try writer.writeAll("    PYTHONNOUSERSITE=1 \\\n");
    try writer.writeAll("    PYTHONSAFEPATH=1\n\n");
    try writer.writeAll("USER 65532:65532\n");
    try writer.writeAll("ENTRYPOINT [\"python\", \"-s\", \"-m\", ");
    try writeJsonString(writer, entrypoint);
    try writer.writeAll("]\n");
}

fn generateNode(writer: *std.Io.Writer, inspection: artifact.Inspection, options: Options) !void {
    const base = try requirePinnedBase(options.base);
    const builder_base = options.builder_base orelse return error.BuilderBaseRequired;
    _ = try requirePinnedBase(builder_base);
    const entrypoint = options.entrypoint orelse return error.InvalidEntrypoint;
    if (!isNodeEntrypoint(entrypoint)) return error.InvalidEntrypoint;
    _ = inspection.node_lock orelse return error.InvalidEntrypoint;

    try writer.writeAll("# Build: install production dependencies without running package scripts.\n");
    try writer.print("FROM {s} AS build\n\n", .{builder_base});
    try writer.writeAll("WORKDIR /src\n");
    try writer.writeAll("COPY ");
    try writeJsonString(writer, options.input);
    try writer.writeAll(" /src\n");
    try writer.writeAll("RUN npm ci \\\n");
    try writer.writeAll("    --omit=dev \\\n");
    try writer.writeAll("    --ignore-scripts \\\n");
    try writer.writeAll("    --no-audit \\\n");
    try writer.writeAll("    --no-fund\n\n");

    try writer.writeAll("# Runtime: application and the pinned Node.js runtime only.\n");
    try writer.print("FROM {s} AS runtime\n\n", .{base});
    try writer.writeAll("COPY --from=build --chown=65532:65532 /src /app\n");
    try generateExtraFiles(writer, options.extra_files, "/app");
    try generateNativeFiles(writer, options);
    try writer.writeAll("\nENV NODE_ENV=production\n\n");
    try writer.writeAll("USER 65532:65532\n");
    try writer.writeAll("ENTRYPOINT [\"/nodejs/bin/node\", ");
    try writeJsonStringWithPrefix(writer, "/app/", entrypoint);
    try writer.writeAll("]\n");
}

fn generateExtraFiles(writer: *std.Io.Writer, files: []const ExtraFile, reserved_path: []const u8) !void {
    for (files) |file| {
        try validateExtraDestination(file.destination, reserved_path);
        try writer.writeAll("COPY --chown=65532:65532 --chmod=0444 ");
        try writeJsonString(writer, file.source);
        try writer.writeByte(' ');
        try writeJsonString(writer, file.destination);
        try writer.writeByte('\n');
    }
}

fn generateNativeFiles(writer: *std.Io.Writer, options: Options) !void {
    if (options.native_files.len == 0) return;
    const root = options.native_root orelse return error.InvalidExtraDestination;
    @import("artifact.zig").validatePortablePath(root) catch return error.InvalidExtraDestination;
    try writer.writeAll("\n# Resolved external commands, interpreters, and recursive ELF dependencies.\n");
    for (options.native_files) |file| {
        try validateExtraDestination(file.destination, "/app");
        try validateExtraDestination(file.destination, "/runtime");
        @import("artifact.zig").validatePortablePath(file.source) catch return error.InvalidExtraDestination;
        if (!std.mem.startsWith(u8, file.source, root) or file.source.len <= root.len or file.source[root.len] != '/') return error.InvalidExtraDestination;
        if (!std.mem.eql(u8, file.source[root.len..], file.destination)) return error.InvalidExtraDestination;
    }
    try writer.writeAll("COPY --chown=65532:65532 --chmod=0555 ");
    try writeJsonString(writer, root);
    try writer.writeAll(" /\n");
    try writer.writeAll("ENV PATH=/usr/local/bin:/usr/bin:/bin\n");
}

fn validateExtraDestination(destination: []const u8, reserved_path: []const u8) error{InvalidExtraDestination}!void {
    if (destination.len < 2 or destination[0] != '/' or destination[destination.len - 1] == '/')
        return error.InvalidExtraDestination;
    if (!std.unicode.utf8ValidateSlice(destination)) return error.InvalidExtraDestination;
    for (destination) |byte| if (byte < 0x20) return error.InvalidExtraDestination;
    if (pathsOverlap(destination, reserved_path))
        return error.InvalidExtraDestination;

    var components = std.mem.splitScalar(u8, destination[1..], '/');
    while (components.next()) |component| {
        if (component.len == 0 or std.mem.eql(u8, component, ".") or std.mem.eql(u8, component, ".."))
            return error.InvalidExtraDestination;
    }
}

fn pathsOverlap(a: []const u8, b: []const u8) bool {
    return std.mem.eql(u8, a, b) or
        (std.mem.startsWith(u8, a, b) and a.len > b.len and a[b.len] == '/') or
        (std.mem.startsWith(u8, b, a) and b.len > a.len and b[a.len] == '/');
}

pub fn requirePinnedBase(base: ?[]const u8) error{ InvalidBase, RuntimeBaseRequired }![]const u8 {
    const value = base orelse return error.RuntimeBaseRequired;
    const marker = "@sha256:";
    const index = std.mem.indexOf(u8, value, marker) orelse return error.InvalidBase;
    const digest = value[index + marker.len ..];
    if (index == 0 or digest.len != 64) return error.InvalidBase;
    for (value[0..index]) |byte| {
        if (!(std.ascii.isAlphanumeric(byte) or byte == '.' or byte == '_' or byte == '-' or
            byte == '/' or byte == ':' or byte == '[' or byte == ']')) return error.InvalidBase;
    }
    for (digest) |byte| {
        if (!std.ascii.isHex(byte) or std.ascii.isUpper(byte)) return error.InvalidBase;
    }
    if (std.mem.indexOfScalar(u8, value, '\n') != null or std.mem.indexOfScalar(u8, value, '\r') != null)
        return error.InvalidBase;
    return value;
}

fn isPythonModule(value: []const u8) bool {
    if (value.len == 0) return false;
    for (value) |byte| {
        if (!(std.ascii.isAlphanumeric(byte) or byte == '_' or byte == '.')) return false;
    }
    return true;
}

fn isNodeEntrypoint(value: []const u8) bool {
    artifact.validatePortablePath(value) catch return false;
    const extension = std.fs.path.extension(value);
    return std.mem.eql(u8, extension, ".js") or
        std.mem.eql(u8, extension, ".mjs") or
        std.mem.eql(u8, extension, ".cjs");
}

fn writeJsonStringWithPrefix(writer: *std.Io.Writer, prefix: []const u8, value: []const u8) std.Io.Writer.Error!void {
    try writer.writeByte('"');
    try writer.writeAll(prefix);
    for (value) |byte| switch (byte) {
        '"' => try writer.writeAll("\\\""),
        '\\' => try writer.writeAll("\\\\"),
        '\n' => try writer.writeAll("\\n"),
        '\r' => try writer.writeAll("\\r"),
        '\t' => try writer.writeAll("\\t"),
        0...8, 11...12, 14...0x1f => try writer.print("\\u00{x:0>2}", .{byte}),
        else => try writer.writeByte(byte),
    };
    try writer.writeByte('"');
}

fn writeJsonString(writer: *std.Io.Writer, value: []const u8) std.Io.Writer.Error!void {
    try writer.writeByte('"');
    for (value) |byte| switch (byte) {
        '"' => try writer.writeAll("\\\""),
        '\\' => try writer.writeAll("\\\\"),
        '\n' => try writer.writeAll("\\n"),
        '\r' => try writer.writeAll("\\r"),
        '\t' => try writer.writeAll("\\t"),
        0...8, 11...12, 14...0x1f => try writer.print("\\u00{x:0>2}", .{byte}),
        else => try writer.writeByte(byte),
    };
    try writer.writeByte('"');
}

test "static ELF uses scratch and a numeric user" {
    const result = try generate(std.testing.allocator, .{
        .kind = .static_elf,
        .architecture = .amd64,
    }, .{ .input = "bin/server" });
    defer std.testing.allocator.free(result);
    try std.testing.expect(std.mem.indexOf(u8, result, "FROM scratch AS runtime\n\n") != null);
    try std.testing.expect(std.mem.indexOf(u8, result, "USER 65532:65532") != null);
}

test "runtime bases must be digest pinned" {
    try std.testing.expectError(error.InvalidBase, requirePinnedBase("python:3.13-slim"));
    try std.testing.expectError(error.InvalidBase, requirePinnedBase("python image@sha256:aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa"));
    try std.testing.expectError(error.RuntimeBaseRequired, requirePinnedBase(null));
    const valid = "registry.example/runtime@sha256:aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa";
    try std.testing.expectEqualStrings(valid, try requirePinnedBase(valid));
}

test "executable stack is rejected" {
    try std.testing.expectError(error.ExecutableStack, generate(std.testing.allocator, .{
        .kind = .static_elf,
        .has_executable_stack = true,
    }, .{ .input = "server" }));
}

test "extra files are copied read-only and cannot replace the application" {
    const result = try generate(std.testing.allocator, .{ .kind = .static_elf }, .{
        .input = "server",
        .extra_files = &.{.{ .source = "config.json", .destination = "/etc/server/config.json" }},
    });
    defer std.testing.allocator.free(result);
    try std.testing.expect(std.mem.indexOf(u8, result, "--chmod=0444 \"config.json\" \"/etc/server/config.json\"") != null);

    try std.testing.expectError(error.InvalidExtraDestination, generate(std.testing.allocator, .{ .kind = .static_elf }, .{
        .input = "server",
        .extra_files = &.{.{ .source = "replacement", .destination = "/app/application" }},
    }));
}

test "Python requires distinct declared build machinery" {
    const digest = "registry.example/python@sha256:aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa";
    try std.testing.expectError(error.BuilderBaseRequired, generate(std.testing.allocator, .{
        .kind = .python_project,
        .python_lock = "requirements.lock",
    }, .{
        .input = "service",
        .base = digest,
        .entrypoint = "service.main",
    }));
}

test "Python uses separate pinned builder and runtime stages" {
    const runtime = "registry.example/python-runtime@sha256:aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa";
    const builder = "registry.example/python-builder@sha256:bbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbb";
    const result = try generate(std.testing.allocator, .{
        .kind = .python_project,
        .python_lock = "requirements.lock",
    }, .{
        .input = "service",
        .base = runtime,
        .builder_base = builder,
        .entrypoint = "service.main",
    });
    defer std.testing.allocator.free(result);
    try std.testing.expect(std.mem.indexOf(u8, result, "FROM " ++ builder ++ " AS build") != null);
    try std.testing.expect(std.mem.indexOf(u8, result, "FROM " ++ runtime ++ " AS runtime\n\n") != null);
    try std.testing.expect(std.mem.indexOf(u8, result, "--require-hashes") != null);
}

